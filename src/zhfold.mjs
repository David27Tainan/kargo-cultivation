// 反查表（0071 前提澄清 (6)：`unfold()` 只用在「顯示 raw fallback」，不用在
// 比對）。一對多時取第一個——ZH_FOLD_MAP 是繁->簡多對一，反過來查會撞到多個
// 繁體字對到同一個簡體字的情況（例如「後」「后」都摺成「后」？實際沒有這組，
// 但規則本身要能處理），這裡固定「先出現的繁體字優先」，跟 Python 端
// `dict` 插入順序一致（JS 物件字面量本身就保留插入順序）。
const UNFOLD_MAP = {};
for (const [trad, simp] of Object.entries(ZH_FOLD_MAP)) {
  if (!(simp in UNFOLD_MAP)) UNFOLD_MAP[simp] = trad;
}

/**
 * 把文字裡的繁體字摺成對應簡體字，只用來算相似度，不可以拿去顯示或存檔。
 * 查不到的字（不在 ZH_FOLD_MAP 裡）原樣保留，不會丟例外（逐字對照
 * zh_fold.py 的 fold()）。
 * @param {string} text
 * @returns {string}
 */
export function fold(text) {
  if (!text) return text;
  let out = "";
  for (const ch of text) {
    out += Object.prototype.hasOwnProperty.call(ZH_FOLD_MAP, ch) ? ZH_FOLD_MAP[ch] : ch;
  }
  return out;
}

/**
 * `fold()` 的反查（0071 前提澄清 (6) 新增，Python 端沒有這個函式）。
 * **只用在顯示 raw fallback**（地圖不在 maps.json 也不在 alias 時，raw 讀值
 * 會是簡體字，這個函式讓畫面上顯示成看起來像繁體的字，但不保證是「正式」
 * 繁體字，也**不用在比對**——比對一律用 `fold()` 把兩邊都摺成簡體）。
 * 一對多（多個繁體字摺成同一個簡體字）時取第一個登記的繁體字。
 * 查不到的字原樣保留。
 * @param {string} text
 * @returns {string}
 */
export function unfold(text) {
  if (!text) return text;
  let out = "";
  for (const ch of text) {
    out += Object.prototype.hasOwnProperty.call(UNFOLD_MAP, ch) ? UNFOLD_MAP[ch] : ch;
  }
  return out;
}
